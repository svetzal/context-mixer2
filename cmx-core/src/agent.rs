    fn preserved_frontmatter_strips_bare_hash_and_hash_space() {
        assert_eq!(
            preserved_frontmatter("# ---\n#x\n#\n#  y\n# ---\n").as_deref(),
            Some("x\n\n y\n")
        );
    }
