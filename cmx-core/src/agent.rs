    #[test]
    fn preserved_frontmatter_round_trips() {
        let md = doc("name: a\nmetadata:\n  version: \"1.3.0\"\n\n  author: me\ndescription: d\n");
        let toml = markdown_to_codex_toml(&md, "x");
        assert_eq!(
            preserved_frontmatter(&toml).as_deref(),
            Some("metadata:\n  version: \"1.3.0\"\n\n  author: me\n")
        );
    }

    #[test]
    fn preserved_frontmatter_none_without_block() {
        assert_eq!(preserved_frontmatter("name = \"a\"\n"), None);
        assert_eq!(preserved_frontmatter("# ---\n# metadata:\nname = \"a\"\n"), None, "unclosed");
        assert_eq!(preserved_frontmatter("# ---\nname = \"a\"\n# ---\n"), None, "non-comment line");
    }

